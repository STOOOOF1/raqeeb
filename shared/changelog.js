// قسم مطوي غير مزعج: تظهر علامة «جديد» صغيرة فقط حتى يُفتح مرة واحدة
CK.whatsNew = function (app) {
  const { h } = CK;
  const who = app === 'kid' ? 'k' : 'p';
  const groups = window.CK_CHANGES.map((g) => ({ ...g, items: g.items.filter((i) => !i.to || i.to === who) })).filter((g) => g.items.length);
  if (!groups.length) return null;
  const latest = groups[0].date, key = 'ck-seen-changes-' + app;
  let seen = ''; try { seen = localStorage.getItem(key) || ''; } catch { /* */ }
  const fmt = (d) => { try { return new Date(d + 'T12:00:00').toLocaleDateString('ar', { day: 'numeric', month: 'long', year: 'numeric' }); } catch { return d; } };
  const dot = seen < latest ? h('span', { class: 'tag pri', style: 'margin-inline-start:6px' }, 'جديد') : null;
  const el = h('details', { class: 'card whatsnew' },
    h('summary', {}, h('span', {}, '🆕 ما الجديد'), dot, h('span', { class: 'small muted', style: 'margin-inline-start:auto' }, 'آخر تحديث ' + fmt(latest))),
    groups.map((g, i) => h('div', { class: 'wn-group' + (i ? ' old' : '') },
      h('div', { class: 'small muted' }, fmt(g.date)),
      h('ul', {}, g.items.map((it) => h('li', {}, it.t))))));
  el.addEventListener('toggle', () => { if (el.open) { try { localStorage.setItem(key, latest); } catch { /* */ } dot?.remove(); } });
  return el;
};
